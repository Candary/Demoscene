# Численная проверка формулы sdTriPrism (IQ) до вставки в шейдер.
# 2D-часть: d2 = max(0.866025*|x| + 0.5*y, -y) - 0.5*h.x
# 3D-часть: d1 = |z| - h.y ; итог = length(max(vec2(d1,d2),0)) + min(max(d1,d2),0)

def sdTriPrism(x, y, z, hx, hy):
    qx, qy, qz = abs(x), abs(y), abs(z)
    d1 = qz - hy
    d2 = max(qx * 0.866025 + qy * 0.5 if False else qx * 0.866025 + y * 0.5, -y) - hx * 0.5
    import math
    dx, dy = max(d1, 0.0), max(d2, 0.0)
    return math.hypot(dx, dy) + min(max(d1, d2), 0.0)

HX, HY = 1.0, 0.5  # как в шейдере: vec2(1.0, 0.5)

cases = [
    # (x, y, z, ожидание: -1 внутри, 0 на поверхности, +1 снаружи, описание)
    (0.0,  0.0,  0.0, -1, "центр (внутри)"),
    (0.0,  0.3,  0.0, -1, "ближе к вершине (внутри)"),
    (0.3, -0.2,  0.0, -1, "у основания (внутри)"),
    (0.0,  0.0,  0.3, -1, "сдвиг по Z (внутри)"),
    (0.0,  1.0,  0.0,  0, "вершина (0, hx) — на поверхности"),
    (0.866025, -0.5, 0.0,  0, "базовая вершина — на поверхности"),
    (-0.866025, -0.5, 0.0, 0, "базовая вершина (симметрия)"),
    (0.0, -0.5,  0.0,  0, "центр основания — на поверхности"),
    (0.0, -0.5,  0.5,  0, "ребро основания (z=+hy)"),
    (0.0,  1.3,  0.0, +1, "над вершиной (снаружи)"),
    (1.2,  0.0,  0.0, +1, "сбоку (снаружи)"),
    (0.0, -0.8,  0.0, +1, "под основанием (снаружи)"),
    (0.0,  0.0,  0.8, +1, "по Z за пределом hy (снаружи)"),
]

fails = 0
for x, y, z, expect, desc in cases:
    d = sdTriPrism(x, y, z, HX, HY)
    if expect == -1: ok, want = d < 0, "d<0"
    elif expect == 0: ok, want = abs(d) < 1e-4, "d≈0"
    else: ok, want = d > 0, "d>0"
    status = "OK  " if ok else "FAIL"
    if not ok: fails += 1
    print(f"{status} ({x:+.4f},{y:+.3f},{z:+.3f}) d={d:+.5f} ожидалось {want:3s} — {desc}")

